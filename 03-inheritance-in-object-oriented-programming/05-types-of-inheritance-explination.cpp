// Description:
//   Inheritance is the process of creating a new class from an
//   existing class. There are different ways in which one class
//   can be inherited from another. These are called types of
//   inheritance.
//
//   1) Single Inheritance
//      In this type one derived class is created from one base class
//      Example: A -> B
//
//   2) Multiple Inheritance
//      In this type one derived class is created from more than one
//      base classes
//      Example: A + B -> C
//
//   3) Multilevel Inheritance
//      In this type a class is derived from another derived class
//      Example: A -> B -> C
//
//   4) Hierarchical Inheritance
//      In this type multiple derived classes are created from a
//      single base class
//      Example: A -> B and A -> C
//
//   5) Hybrid Inheritance
//      In this type a combination of more than one inheritance type
//      is used together such as multiple plus multilevel
//
// Note: In real world programming the choice of inheritance type
// depends on the design of the problem


