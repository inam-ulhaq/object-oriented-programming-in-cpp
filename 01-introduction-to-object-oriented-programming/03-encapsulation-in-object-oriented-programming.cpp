// Description:
// 	  Encapsulation is one of the core concepts in Object-Oriented Programming.
// It refers to the practice of bundling data (attributes) and methods
// (functions) that operate on the data into a single unit, or class.
// It involves restricting access to the internal details using access 
// modifiers like private, protected, and public for data protection.

// In short, encapsulation means grouping data and methods together, 
// hiding the internal state of an object and exposing only a 
// controlled interface to the outside world (other parts of the program).

// Key Concepts of Encapsulation:

// 1. **Private Data**: 
// Internal data (attributes) is made private, restricting direct access.
// This prevents mishandling or modifying the data in ways that 
// could break the program's integrity.

// 2. **Public Methods (Getter/Setter)**:
// The internal data can only be accessed or modified through 
// public methods (getter and setter functions), which act as 
// a controlled interface to the private data, ensuring validation.

// 3. **Protecting Data Integrity**:
// Encapsulation ensures validation and control of changes to data, 
// preventing the assignment of invalid values like negative balances.
// This maintains data consistency and integrity.

// 4. **Code Maintainability**:
// Encapsulation allows the internal implementation of a class to 
// be changed without affecting external code. The external code 
// interacts only with the public interface, ensuring flexibility.
