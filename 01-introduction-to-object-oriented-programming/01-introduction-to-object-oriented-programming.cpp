// Description: 
//      Object oriented programming (OOP) is a strategy or style of developing applications.
//      Like other methodologies such as structural, procedural or aspect programming, OOP
//      gives its own way of designing and building software.
//
//      - Object oriented programming is mainly related to the internal design of a software,
//        not to the visible design of a program. It’s not directly related to the user of
//        the software but to the programmer who develops it.
//
//      - With the help of object orientation, programming becomes more systematic and follows
//        an engineering process. In other fields of engineering, a product is planned and
//        designed before it’s built. In the same way, a software product can be developed by
//        adopting object orientation.
//
//      - Example: suppose a civil engineer is constructing a building. First he makes a plan
//        and a design. Once the design is finalized he prepares a blueprint. Based on that
//        blueprint the actual building is constructed.  
//        In the same way in object oriented programming first we design a class (which acts as
//        a blueprint). After the class is ready (the design complete) we create objects from
//        that class (like constructing the building from the blueprint).