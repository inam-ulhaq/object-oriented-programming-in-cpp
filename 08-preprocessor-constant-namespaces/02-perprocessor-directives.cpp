// Title: Preprocessor Directives
// Author: Inam Ul Haq
// Description:
//    Preprocessor directives in C/C++ are instructions given to the compiler 
//    before the actual compilation process begins. They start with `#` 
//    and are handled by the preprocessor. 
//
// Key Points:
//    -> #include -> used to include header files in the program
//    -> #define -> used to define macros or constants
//    -> #undef -> used to undefine a macro
//    -> #ifdef -> checks if a macro is defined
//    -> #ifndef -> checks if a macro is not defined
//    -> #if -> allows conditional compilation based on an expression
//    -> #else -> provides alternative compilation path
//    -> #elif -> else if condition in preprocessor
//    -> #endif -> ends conditional compilation
//    -> #pragma -> gives special instructions to the compiler (e.g., disable warnings)
//
// Purpose:
//    -> Allows code reusability with header files
//    -> Improves readability with constants/macros
//    -> Controls conditional compilation
//    -> Optimizes build process
