// Title: Namespace
// Author: Inam Ul Haq
// Description:
//    A namespace in C++ is used to organize code into logical groups and 
//    to avoid name conflicts between identifiers (such as variables, 
//    functions, classes). It acts as a scope container. 
//
// Key Points:
//    -> namespace keyword -> defines a named scope
//    -> Namespaces help in preventing name collisions in large projects
//    -> The scope resolution operator (::) is used to access members of a namespace
//    -> A namespace can contain variables, functions, classes, and objects
//    -> Nested namespaces are allowed
//    -> Anonymous namespace (namespace { }) -> members have internal linkage 
//    -> The 'using' directive -> allows direct access without specifying namespace each time
//
// Purpose:
//    -> Provides better code organization
//    -> Prevents conflicts when multiple libraries have same identifier names
//    -> Improves readability and maintainability
